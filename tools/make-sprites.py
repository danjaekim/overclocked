#!/usr/bin/env python3
"""Builds src/render/sprite-art.js from the locked-in character designs in the art canvas.

The designs live as SVG <symbol>s inside the art project's .dc.html boards. Pass the project
directory (the one holding Smith.dc.html, Archer2.dc.html, ...). Run only when a design changes.
"""
import re, sys, pathlib

SRC = pathlib.Path(sys.argv[1])
PICK = {                       # class id -> (board file, symbol id, board's filter id)
    'smith':     ('Smith.dc.html',     's-b', 's-rough'),
    'archer':    ('Archer2.dc.html',   'r-3', 'r-rough'),
    'mage':      ('Mage2.dc.html',     'g-2', 'g-rough'),
    'berserker': ('Berserker.dc.html', 'b-2', 'b-rough'),
    'summoner':  ('Summoner.dc.html',  'u-2', 'u-rough'),
    'saint':     ('Saint.dc.html',     'h-1', 'h-rough'),
    'goblin':    ('Goblin2.dc.html',   'o-1', 'o-rough'),     # Clubber
    'brute':     ('Brute2.dc.html',    'k-1', 'k-rough'),     # Boulder
    'warlord':   ('Warlord2.dc.html',  'w-1', 'w-rough'),     # Ogre King
    # loot and props: set C (orbs, ingots, strongbox, forge altar) from Pickups.dc.html
    'gem0':      ('Pickups.dc.html',   'p-C-g0',    'p-rough'),
    'gem1':      ('Pickups.dc.html',   'p-C-g1',    'p-rough'),
    'gem2':      ('Pickups.dc.html',   'p-C-g2',    'p-rough'),
    'gem3':      ('Pickups.dc.html',   'p-C-g3',    'p-rough'),
    'ore_iron':  ('Pickups.dc.html',   'p-C-iron',  'p-rough'),
    'ore_starsteel': ('Pickups.dc.html', 'p-C-star', 'p-rough'),
    'chest':     ('Pickups.dc.html',   'p-C-chest', 'p-rough'),
    'bosschest': ('Pickups.dc.html',   'p-C-boss',  'p-rough'),
    'shrine':    ('Pickups.dc.html',   'p-C-anvil', 'p-rough'),
}
# Variants built on a locked design: the base symbol plus a few extra shapes in the same woodcut
# style (id -> extra SVG drawn on top). Placeholders until they get their own art round.
STYLE = 'filter="url(#rough)" fill="#1d1713" stroke="#e9dcc0" stroke-width="2" stroke-linejoin="round" stroke-linecap="round"'
EXTRA = {
    'shieldbearer': ('goblin', '<g %s>'
        '<path d="M19 25 Q18 10 32 10 Q46 10 45 25 L41 22 H23 Z" fill="#8fa3b8"/>'
        '<path d="M32 10 V3" stroke="#e8531e" stroke-width="3"/>'
        '<path d="M14 34 L27 38 L25 53 L14 60 L3 53 L1 38 Z" fill="#8fa3b8"/>'
        '<path d="M14 38 V57 M5 46 H23" stroke="#1d1713" stroke-width="2.200" fill="none"/>'
        '</g>' % STYLE),
    'slinger': ('goblin', '<g %s>'
        '<path d="M10 20 Q-2 40 10 60" fill="none" stroke="#e9dcc0" stroke-width="5"/>'
        '<path d="M10 20 Q-2 40 10 60" fill="none" stroke="#8c7b66" stroke-width="2.400"/>'
        '<path d="M10 20 L10 60" fill="none" stroke="#e9dcc0" stroke-width="1.200"/>'
        '<path d="M24 20 H40 V27 H24 Z" fill="#b06ad0" stroke-width="1.600"/>'
        '</g>' % STYLE),
    'splitter': ('goblin', '<g %s>'
        '<path d="M22 46 Q32 38 42 46 Q44 58 32 59 Q20 58 22 46 Z" fill="#d98cae"/>'
        '<path d="M32 40 L29 48 L34 52 L31 59 M26 50 L21 54 M38 48 L44 52" fill="none" stroke="#1d1713" stroke-width="2"/>'
        '<circle cx="32" cy="51" r="3.200" fill="#ffe3f0" stroke-width="1.200"/>'
        '</g>' % STYLE),
    'shaman': ('goblin', '<g %s>'
        '<path d="M18 27 Q16 8 32 7 Q48 8 46 27 L40 20 H24 Z" fill="#3f7f86"/>'
        '<path d="M8 62 L9 16" fill="none" stroke="#e9dcc0" stroke-width="5"/>'
        '<path d="M8 62 L9 16" fill="none" stroke="#8c7b66" stroke-width="2.400"/>'
        '<circle cx="9" cy="11" r="6" fill="#5aa8b0"/>'
        '<circle cx="7.500" cy="9.500" r="1.800" fill="#e9dcc0" stroke-width="0"/>'
        '</g>' % STYLE),
}
FILTER = ('<filter id="rough" x="-8%" y="-8%" width="116%" height="116%">'
          '<feTurbulence type="fractalNoise" baseFrequency="0.07" numOctaves="2" seed="4" result="n"/>'
          '<feDisplacementMap in="SourceGraphic" in2="n" scale="2.6"/></filter>')

INNER = {}
out = ['// GENERATED by tools/make-sprites.py from the art canvas. Do not edit by hand.',
       '// Player, enemy and loot art as SVG strings (woodcut ink style, 64x64 design grid).', '',
       'export const SPRITE_VIEWBOX = \'-6 -6 76 76\';', 'export const SPRITE_ART = {']
for cid, (fname, sym, filt) in PICK.items():
    text = (SRC / fname).read_text()
    m = re.search(r'<symbol id="%s"[^>]*>(.*?)</symbol>' % re.escape(sym), text, re.S)
    inner = m.group(1)
    inner = re.sub(r'<use href="#u-hound"[^>]*/>\n?', '', inner)      # the game draws the hounds itself
    inner = inner.replace('url(#%s)' % filt, 'url(#rough)')
    inner = re.sub(r'\s*\n\s*', '', inner)
    INNER[cid] = inner
    svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="-6 -6 76 76"><defs>%s</defs>%s</svg>' % (FILTER, inner)
    assert '<use' not in svg and 'url(#' in svg
    out.append("  %s: %r," % (cid, svg))
for vid, (base, extra) in EXTRA.items():
    svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="-6 -6 76 76"><defs>%s</defs>%s%s</svg>' % (FILTER, INNER[base], extra)
    assert '<use' not in svg
    out.append("  %s: %r," % (vid, svg))
out.append('};')
dest = pathlib.Path(__file__).resolve().parent.parent / 'src' / 'render' / 'sprite-art.js'
dest.write_text('\n'.join(out) + '\n')
print('wrote', dest, dest.stat().st_size, 'bytes')
