#!/usr/bin/env python3
"""Builds src/render/sprite-art.js from the locked-in character designs in the art canvas.

The designs live as SVG <symbol>s inside the art project's .dc.html boards. Pass the project
directory (the one holding Smith.dc.html, Archer2.dc.html, ...). Run only when a design changes.
"""
import re, sys, pathlib

SRC = pathlib.Path(sys.argv[1])
PICK = {                       # class id -> (board file, symbol id, board's filter id)
    'smith':     ('Smith.dc.html',     's-b', 's-rough'),
    'archer':    ('Archer2.dc.html',   'r-3', 'r-rough'),
    'mage':      ('Mage2.dc.html',     'g-2', 'g-rough'),
    'berserker': ('Berserker.dc.html', 'b-2', 'b-rough'),
    'summoner':  ('Summoner.dc.html',  'u-2', 'u-rough'),
    'saint':     ('Saint.dc.html',     'h-1', 'h-rough'),
    'goblin':    ('Goblin2.dc.html',   'o-1', 'o-rough'),     # Clubber
    'brute':     ('Brute2.dc.html',    'k-1', 'k-rough'),     # Boulder
    'warlord':   ('Warlord2.dc.html',  'w-1', 'w-rough'),     # Ogre King
}
FILTER = ('<filter id="rough" x="-8%" y="-8%" width="116%" height="116%">'
          '<feTurbulence type="fractalNoise" baseFrequency="0.07" numOctaves="2" seed="4" result="n"/>'
          '<feDisplacementMap in="SourceGraphic" in2="n" scale="2.6"/></filter>')

out = ['// GENERATED by tools/make-sprites.py from the art canvas. Do not edit by hand.',
       '// Player and enemy art as SVG strings (woodcut ink style, 64x64 design grid).', '',
       'export const SPRITE_VIEWBOX = \'-6 -6 76 76\';', 'export const SPRITE_ART = {']
for cid, (fname, sym, filt) in PICK.items():
    text = (SRC / fname).read_text()
    m = re.search(r'<symbol id="%s"[^>]*>(.*?)</symbol>' % re.escape(sym), text, re.S)
    inner = m.group(1)
    inner = re.sub(r'<use href="#u-hound"[^>]*/>\n?', '', inner)      # the game draws the hounds itself
    inner = inner.replace('url(#%s)' % filt, 'url(#rough)')
    inner = re.sub(r'\s*\n\s*', '', inner)
    svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="-6 -6 76 76"><defs>%s</defs>%s</svg>' % (FILTER, inner)
    assert '<use' not in svg and 'url(#' in svg
    out.append("  %s: %r," % (cid, svg))
out.append('};')
dest = pathlib.Path(__file__).resolve().parent.parent / 'src' / 'render' / 'sprite-art.js'
dest.write_text('\n'.join(out) + '\n')
print('wrote', dest, dest.stat().st_size, 'bytes')
